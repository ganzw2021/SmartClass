def create_table():
    """创建中药表"""
    conn = pymysql.connect(**DB_CONFIG)
    cur = conn.cursor()
    
    # 创建表
    cur.execute("""
        CREATE TABLE IF NOT EXISTS herbs (
            id INT AUTO_INCREMENT PRIMARY KEY,
            name VARCHAR(50) NOT NULL COMMENT '中药名称',
            category VARCHAR(50) NOT NULL COMMENT '中药分类',
            efficacy TEXT NOT NULL COMMENT '功效',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            UNIQUE KEY uk_name (name)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='中药数据库'
    """)
    
    conn.commit()
    cur.close()
    conn.close()
    print("[OK] 中药表创建成功")


def import_herbs():
    """导入中药数据"""
    conn = pymysql.connect(**DB_CONFIG)
    cur = conn.cursor()
    
    total = 0
    for category, herbs in HERBS_DATA.items():
        for herb in herbs:
            name, efficacy = herb
            try:
                cur.execute(
                    "INSERT IGNORE INTO herbs (name, category, efficacy) VALUES (%s, %s, %s)",
                    (name, category, efficacy)
                )
                if cur.rowcount > 0:
                    total += 1
            except Exception as e:
                print(f"导入 {name} 失败: {e}")
    
    conn.commit()
    cur.close()
    conn.close()
    print(f"[OK] 成功导入 {total} 条中药数据")


def show_stats():
    """显示统计信息"""
    conn = pymysql.connect(**DB_CONFIG)
    cur = conn.cursor()
    
    # 总数
    cur.execute("SELECT COUNT(*) FROM herbs")
    total = cur.fetchone()[0]
    
    # 分类统计
    cur.execute("SELECT category, COUNT(*) as cnt FROM herbs GROUP BY category ORDER BY cnt DESC")
    categories = cur.fetchall()
    
    print(f"\n[STATS] 中药数据库统计:")
    print(f"总数据: {total} 条")
    print("\n分类统计:")
    for cat, cnt in categories:
        print(f"  {cat}: {cnt} 条")
    
    cur.close()
    conn.close()


